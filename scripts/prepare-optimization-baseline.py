from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
REVISION = "bb5cd35842e420330f799d7e2dc46b43dc0e8bfa"
DESTINATION = ROOT / "src-tauri/tests/fixtures/optimization-baseline"
DESTINATION.mkdir(parents=True, exist_ok=True)
for name in ("storage", "search"):
    source = subprocess.check_output(
        ["git", "show", f"{REVISION}:src-tauri/src/{name}.rs"], cwd=ROOT, text=True
    ).split("\n#[cfg(test)]")[0]
    if name == "storage":
        source = source.replace("pub mod transfer;", "")
    else:
        source = source.replace("    storage::MemorySummary,\n", "")
        source = "use super::baseline_storage::MemorySummary;\n" + source
    (DESTINATION / f"{name}.rs").write_text(
        f"// Generated by scripts/prepare-optimization-baseline.py from {REVISION}; do not edit.\n{source.rstrip()}\n"
    )
