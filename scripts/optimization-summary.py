def latest(pattern):
    paths = sorted(path for path in BASE.glob(pattern) if path.is_file())
    if not paths:
        raise SystemExit(f"Missing acceptance report: {pattern}")
    return paths[-1], json.loads(paths[-1].read_text())


def link(path):
    return f"[{path.name}](../{path.relative_to(ROOT).as_posix()})"


def rank(result, expected):
    if not result:
        return None
    return next((i + 1 for i, hit in enumerate(result["results"]) if hit["id"] in expected), None)


